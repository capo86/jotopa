test('UI aislada: renovación sin descargar de nuevo una foto visible y retorno gradual',async({page})=>{
  await page.clock.install()
  const photos=await webpFixtures(page),fixture=await projectionFixture(page,{count:3,photos})
  await openScreen(page)
  await page.getByRole('button',{name:'Últimos mensajes',exact:true}).click()
  const image=page.locator('.wp-history img');await expect(image).toBeVisible();await expect.poll(()=>image.evaluate(element=>element.complete&&element.naturalWidth>0)).toBe(true)
  const downloaded=fixture.photoRequests,signatures=fixture.signatures
  fixture.offset=46000;await page.clock.fastForward(46000)
  await expect.poll(()=>fixture.signatures).toBeGreaterThan(signatures)
  expect(fixture.photoRequests).toBe(downloaded)
  const history=page.getByLabel('Historial completo de buenos deseos',{exact:true})
  await history.evaluate(element=>{element.scrollTop=element.scrollHeight})
  const end=await history.evaluate(element=>element.scrollTop)
  await page.getByRole('button',{name:'Iniciar recorrido automático',exact:true}).click()
  await page.clock.runFor(7000);expect(await history.evaluate(element=>element.scrollTop)).toBeGreaterThanOrEqual(end-1)
  await page.clock.runFor(1600);const returning=await history.evaluate(element=>element.scrollTop)
  expect(returning).toBeLessThan(end);expect(returning).toBeGreaterThan(Math.max(0,end-70))
  await page.getByRole('button',{name:'Pausar recorrido',exact:true}).click()
  const paused=await history.evaluate(element=>element.scrollTop);await page.clock.runFor(1000);expect(await history.evaluate(element=>element.scrollTop)).toBe(paused)
})

test('UI aislada: activación explícita, restricción del navegador, voces exclusivas y retirada durante audio',async({page})=>{
  const photos=await webpFixtures(page),fixture=await projectionFixture(page,{photos,audioDuration:5})
  fixture.put(fixture.makePost(1,'Primera voz.',[fixture.voice(1)]));fixture.put(fixture.makePost(2,'Segunda voz.',[fixture.voice(2)]))
  await openScreen(page)
  const audios=page.locator('.wp-history audio');await expect(audios).toHaveCount(2)
  await page.evaluate(()=>{
    const original=HTMLMediaElement.prototype.play
    HTMLMediaElement.prototype.play=function(){HTMLMediaElement.prototype.play=original;return Promise.reject(new DOMException('Simulated blocked gesture','NotAllowedError'))}
  })
  await page.getByRole('button',{name:'Activar audio',exact:true}).click()
  await expect(page.locator('.wp-screen-note')).toContainText('El navegador requiere')
  await page.getByRole('button',{name:'Activar audio',exact:true}).click()
  await expect.poll(()=>audios.evaluateAll(elements=>elements.filter(element=>!element.paused).length)).toBe(1)
  await audios.nth(1).evaluate(async element=>{await element.play()})
  await expect.poll(()=>audios.nth(0).evaluate(element=>element.paused)).toBe(true)
  await expect(page.getByRole('button',{name:'Pausar recorrido',exact:true})).toBeVisible()
  await expect(page.locator('.wp-screen-note')).toContainText('en pausa mientras')
  await expect.poll(()=>audios.nth(1).evaluate(element=>element.ended),{timeout:10000}).toBe(true)
  await expect(page.locator('.wp-screen-note')).not.toContainText('en pausa mientras')
  await audios.nth(1).evaluate(async element=>{element.currentTime=0;await element.play()})
  const removed=await audios.nth(1).elementHandle()
  fixture.hide(fixture.uuid(2));fixture.notify()
  await expect(page.getByText('Segunda voz.',{exact:true})).toHaveCount(0,{timeout:15000})
  expect(await removed.evaluate(element=>element.paused&&!element.getAttribute('src'))).toBe(true)
  await expect(page.locator('.wp-screen-note')).not.toContainText('en pausa mientras')
})
